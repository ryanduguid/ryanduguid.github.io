//! scripts/build_llms_full.py: build llms-full.txt, its section parts, the per-page
//! index.txt copies, the closing part index of llms.txt and the identical
//! .well-known/llms.txt index copy.
//!
//! Run with --write to regenerate the files, or --check to fail when any is stale. The
//! full text is derived from the visible <main> content only, so the machine copy can
//! never say more than the page does.
use crate::html::unescape;
use crate::py;
use crate::pyre::{I, S, re};
use crate::seo_core::{self as core, Tree};
use std::collections::HashSet;
use std::path::{Path, PathBuf};

const SITE: &str = "https://duguid.com.au";
const MAIN_PATTERN: &str = r"<main\b[^>]*>(.*?)</main>";
// Only wayfinding navigation is dropped: breadcrumbs and on-this-page contents.
// Navigation that carries content (tool categories, related pages, actions,
// workbook and source-project links) stays in the text.
const WAYFINDING_NAV_PATTERN: &str =
    r#"<nav\b[^>]*\bclass="[^"]*\barticle-(?:crumb|toc)\b[^"]*"[^>]*>.*?</nav>"#;
const PRE_PATTERN: &str = r"<pre\b[^>]*>(.*?)</pre>";
const HEADING_PATTERN: &str = r"<h([1-4])\b[^>]*>(.*?)</h\1>";
const BLOCK_PATTERN: &str = concat!(
    r"</?(?:p|div|section|article|header|footer|ul|ol|dl|dt|dd|blockquote|table|",
    r"thead|tbody|tr|figure|figcaption|details|summary|br|hr)\b[^>]*>"
);
const LI_PATTERN: &str = r"<li\b[^>]*>";
const CELL_PATTERN: &str = r"</t[dh]>\s*<t[dh]\b[^>]*>";
const TAG_PATTERN: &str = r"<[^>]+>";
const HEADER: &str = concat!(
    "# duguid.com.au, full text\n\n",
    "Every indexable page of https://duguid.com.au/ as plain text, in sitemap ",
    "order, built from the visible main content of each page. Link destinations ",
    "follow each page's text. The short index ",
    "is https://duguid.com.au/llms.txt. Nothing here is tax, legal, or financial ",
    "advice; verify figures against current guidance before relying on them.\n\n",
    "Generated by site-tools build_llms_full. Do not edit by hand.\n",
);
const RERUN: &str = "run site-tools build_llms_full --write";

fn page_path(url: &str, content_root: &Path, name: &str) -> PathBuf {
    let rel = url.strip_prefix(SITE).unwrap_or(url).trim_matches('/');
    if rel.is_empty() {
        content_root.join(name)
    } else {
        content_root.join(format!("{rel}/{name}"))
    }
}

fn block_kind(block: &str) -> &'static str {
    if block.starts_with("- ") {
        "item"
    } else if block.contains(" | ") {
        "row"
    } else {
        "text"
    }
}

/// A <pre> block as a fenced block with its line breaks and indentation kept.
fn preformatted(inner: &str) -> String {
    let text = unescape(&re(TAG_PATTERN, 0).sub("", inner));
    let lines: Vec<&str> = py::splitlines(text.trim_matches('\n'))
        .into_iter()
        .map(|line| line.trim_end_matches(py::is_space))
        .collect();
    format!("```\n{}\n```", lines.join("\n"))
}

/// The visible main content of a page as plain text, with its link destinations.
pub fn main_text(html: &str, page_url: &str) -> Result<String, String> {
    let matches = re(MAIN_PATTERN, S | I).findall(html);
    if matches.len() != 1 {
        return Err("llms-full: page must have exactly one <main>".into());
    }
    let body = core::visible_html(&re(WAYFINDING_NAV_PATTERN, S | I).sub(" ", &matches[0]));
    let mut pres: Vec<String> = Vec::new();
    let body = re(PRE_PATTERN, S | I).sub_with(&body, |m| {
        pres.push(preformatted(&m[1]));
        format!("\n\nPREFORMATTED-{}\n\n", pres.len() - 1)
    });
    // A card's bold title and its description read as one sentence without a
    // separator, so the title gets a colon: "Payday Super timing: Reproduce ...".
    let body =
        re(r"</strong>(\s*)<span\b", 0).sub_with(&body, |m| format!(":</strong>{}<span", &m[1]));
    let mut links: Vec<(String, String)> = Vec::new();
    let mut seen: HashSet<String> = HashSet::new();
    let tree: Tree = core::parse_structure(&body);
    for anchor in tree.descendants(Tree::ROOT, Some("a"), false) {
        let href = tree.attr(anchor, "href").unwrap_or("");
        let label = tree.text(anchor);
        if !href.is_empty() && !label.is_empty() {
            let target = crate::pyurl::urljoin(page_url, href)?;
            let scheme = crate::pyurl::urlsplit(&target)?.scheme;
            if (scheme == "http" || scheme == "https") && seen.insert(target.clone()) {
                links.push((target, label));
            }
        }
    }
    let body = re(HEADING_PATTERN, S | I).sub_with(&body, |m| {
        let level: usize = m[1].parse().expect("one ASCII digit");
        format!("\n\n{} {}\n\n", "#".repeat(level), &m[2])
    });
    let body = re(LI_PATTERN, I).sub("\n\n- ", &body);
    let body = re(CELL_PATTERN, S | I).sub(" | ", &body);
    let body = re(BLOCK_PATTERN, I).sub("\n\n", &body);
    // Adjacent inline elements such as 2 links keep a space between them. A
    // closing tag followed by another closing tag or by punctuation gets none,
    // so "<a><em>Act 1997</em></a>." does not become "Act 1997 .".
    let body =
        re(r"(</[a-zA-Z0-9]+>)(<[a-zA-Z])", 0).sub_with(&body, |m| format!("{} {}", &m[1], &m[2]));
    let body = unescape(&re(TAG_PATTERN, 0).sub("", &body));
    // Removing hidden link context can strand a space before the next comma or stop.
    // Only punctuation that ends a word counts, so ".claude/skills/" keeps its space.
    let stranded = re(r"(?<!\s)\s+([,.;:!?])(?=\s|$)", 0);
    let blocks: Vec<String> = re(r"\n\s*\n", 0)
        .split(&body)
        .into_iter()
        .map(|block| {
            let block = py::strip(&re(r"\s+", 0).sub(" ", block)).to_owned();
            stranded.sub_with(&block, |m| m[1].to_owned())
        })
        .collect();
    let mut text = String::new();
    let mut previous = "text";
    for block in blocks.iter().filter(|b| !b.is_empty()) {
        let kind = block_kind(block);
        let joined = kind != "text" && kind == previous;
        text.push_str(if joined { "\n" } else { "\n\n" });
        text.push_str(block);
        previous = kind;
    }
    let mut missing = None;
    let mut text = re(r"PREFORMATTED-(\d+)", 0).sub_with(&text, |m| {
        let block = py::parse_int(&m[1], 10)
            .ok()
            .and_then(|i| usize::try_from(i).ok())
            .and_then(|i| pres.get(i));
        match block {
            Some(block) => block.clone(),
            None => {
                missing.get_or_insert_with(|| "IndexError: list index out of range".to_owned());
                String::new()
            }
        }
    });
    if let Some(error) = missing {
        return Err(error);
    }
    if !links.is_empty() {
        text.push_str("\n\n## Links\n\n");
        let lines: Vec<String> = links
            .iter()
            .map(|(url, label)| format!("- {label}: {url}"))
            .collect();
        text.push_str(&lines.join("\n"));
    }
    Ok(py::strip(&text).to_owned())
}

/// Each indexable page's entry keyed by URL, in sitemap order.
pub fn build(root: &Path) -> Result<Vec<(String, String)>, String> {
    let mut content_root = root.to_path_buf();
    if root.join("Gemfile").is_file() {
        // Render Liquid data and includes before extracting the visible text.
        content_root = crate::build_site::build(root, root)?;
    }
    let mut entries: Vec<(String, String)> = Vec::new();
    for url in core::sitemap_urls(root)? {
        let html = crate::read(&page_path(&url, &content_root, "index.html"))?;
        let Some(title) = re(r"<title>(.*?)</title>", S).search(&html) else {
            return Err(format!("ValueError: {url}: page has no <title>"));
        };
        let title = py::strip(&unescape(&title[1])).to_owned();
        let description = core::meta(&html, "name", "description").unwrap_or_default();
        let entry = format!(
            "# {title}\n\nSource: {url}\n\n> {description}\n\n{}\n",
            main_text(&html, &url)?
        );
        // A repeated sitemap URL keeps its first position, as a dict key does.
        match entries.iter_mut().find(|(u, _)| *u == url) {
            Some(existing) => existing.1 = entry,
            None => entries.push((url, entry)),
        }
    }
    Ok(entries)
}

pub fn full_text(entries: &[(String, String)]) -> String {
    let mut parts = vec![HEADER.to_owned()];
    parts.extend(entries.iter().map(|(_, entry)| format!("---\n\n{entry}")));
    parts.join("\n")
}

/// Section files keep complete page entries and their citations below 100 KB.
pub fn section_parts(entries: &[(String, String)]) -> Result<Vec<(String, String)>, String> {
    let mut sections = std::collections::BTreeMap::<String, Vec<String>>::new();
    for (url, entry) in entries {
        let section = url
            .strip_prefix(SITE)
            .unwrap_or(url)
            .trim_matches('/')
            .split('/')
            .next()
            .filter(|s| !s.is_empty())
            .unwrap_or("home");
        sections
            .entry(section.into())
            .or_default()
            .push(format!("---\n\n{entry}"));
    }
    let mut parts = Vec::new();
    for (section, pages) in sections {
        let mut text = HEADER.to_owned();
        let mut number = 1;
        for page in pages {
            if HEADER.len() + page.len() + 1 > 96_000 {
                return Err(format!(
                    "llms-full: {section} page exceeds the section part budget"
                ));
            }
            if text.len() + page.len() + 1 > 96_000 {
                parts.push((format!("llms-full-{section}-{number}.txt"), text));
                number += 1;
                text = HEADER.to_owned();
            }
            text.push('\n');
            text.push_str(&page);
        }
        parts.push((format!("llms-full-{section}-{number}.txt"), text));
    }
    Ok(parts)
}

const PART_INDEX_HEADING: &str = "## Full text by section";

/// The closing section of llms.txt: each part file and the page titles it holds, so a
/// reader can fetch only the part it needs.
pub fn part_index(parts: &[(String, String)]) -> String {
    let mut out = format!(
        "{PART_INDEX_HEADING}\n\nThe complete file remains at {SITE}/llms-full.txt. \
         Each section part is below 100 KB; the pages it holds follow its link. \
         Generated by site-tools build_llms_full.\n\n"
    );
    for (name, text) in parts {
        let mut titles = Vec::new();
        let mut lines = text.lines();
        while let Some(line) = lines.next() {
            if line == "---"
                && let Some(title) = lines
                    .find(|l| !l.is_empty())
                    .and_then(|l| l.strip_prefix("# "))
            {
                titles.push(title);
            }
        }
        out.push_str(&format!(
            "- [{name}]({SITE}/{name}): {}\n",
            titles.join("; ")
        ));
    }
    out
}

/// llms.txt with its closing part index replaced by the generated one.
pub fn with_part_index(index: &str, parts: &[(String, String)]) -> Result<String, String> {
    let Some(start) = index.find(&format!("\n{PART_INDEX_HEADING}\n")) else {
        return Err(format!("llms.txt: no {PART_INDEX_HEADING:?} section"));
    };
    Ok(format!("{}\n{}", &index[..start], part_index(parts)))
}

fn read_text(path: &Path) -> Result<String, String> {
    if path.is_file() {
        crate::read(path)
    } else {
        Ok(String::new())
    }
}

fn write(path: &Path, bytes: &[u8]) -> Result<(), String> {
    std::fs::write(path, bytes)
        .map_err(|e| py::oserror_str(&e, &path.to_string_lossy(), py::OsStyle::Errno))
}

fn say(text: &str) -> Result<(), String> {
    crate::print_text(text, false).map_err(|e| e.to_string())
}

pub fn run(root: &Path, args: &[String]) -> Result<u8, String> {
    let entries = build(root)?;
    let built = full_text(&entries);
    let parts = section_parts(&entries)?;
    let index_path = root.join("llms.txt");
    let current = crate::read(&index_path)?;
    let index = with_part_index(&current, &parts)?.into_bytes();
    let output = root.join("llms-full.txt");
    let alias = root.join(".well-known/llms.txt");
    if args.iter().any(|a| a == "--write") {
        write(&index_path, &index)?;
        write(&output, built.as_bytes())?;
        for (name, content) in &parts {
            write(&root.join(name), content.as_bytes())?;
        }
        for (url, entry) in &entries {
            write(&page_path(url, root, "index.txt"), entry.as_bytes())?;
        }
        let parent = alias.parent().expect("a parent");
        std::fs::create_dir_all(parent)
            .map_err(|e| py::oserror_str(&e, &parent.to_string_lossy(), py::OsStyle::Errno))?;
        write(&alias, &index)?;
        say(&format!(
            "llms-full.txt and {} index.txt pages written\n.well-known/llms.txt copied from llms.txt\n",
            entries.len()
        ))?;
        return Ok(0);
    }
    if current.as_bytes() != index {
        say(&format!("llms.txt part index is stale: {RERUN}\n"))?;
        return Ok(1);
    }
    if read_text(&output)? != built {
        say(&format!("llms-full.txt is stale: {RERUN}\n"))?;
        return Ok(1);
    }
    for (name, content) in &parts {
        if read_text(&root.join(name))? != *content {
            say(&format!("{name} is stale: {RERUN}\n"))?;
            return Ok(1);
        }
    }
    let mut stale = 0;
    for (url, entry) in &entries {
        if read_text(&page_path(url, root, "index.txt"))? != *entry {
            stale += 1;
        }
    }
    if stale > 0 {
        say(&format!("{stale} index.txt page(s) stale: {RERUN}\n"))?;
        return Ok(1);
    }
    if !alias.is_file() || std::fs::read(&alias).map_err(|e| e.to_string())? != index {
        say(&format!(".well-known/llms.txt is stale: {RERUN}\n"))?;
        return Ok(1);
    }
    say(&format!(
        "llms-full.txt matches its pages ({} pages)\n.well-known/llms.txt matches llms.txt\n",
        built.matches("Source: ").count()
    ))?;
    Ok(0)
}
